// Transparentnost podle EU AI Act čl. 50(1): kdo se zeptá, jestli mluví s AI, má
// dostat jasnou odpověď — deterministicky, dřív než cokoli jiného (převzato z Viktorky,
// kde 13. 8. 2026 topic-guard na takový dotaz odpověděl odmítnutím, protože se k modelu
// vůbec nedostal). Odpověď skládá server, ne model.

// Uzavřený seznam formulací — ne obecné „obsahuje AI", aby „ukaž AI projekty"
// nespadlo do disclosure.
const DISCLOSURE_PATTERNS = [
  // CZ — přímé
  /(?:jsi|jste|seš|ses|si)\s+(?:vlastne\s+|nahodou\s+|opravdu\s+|fakt\s+|jenom\s+|jen\s+)?(?:nejak\w*\s+)?(?:a\s?i|ai|umel\w* inteligenc\w*|robot\w*|bot\w*|chatbot\w*|stroj|program\w*|pocitac\w*)/,
  /(?:jsi|jste|seš)\s+(?:vlastne\s+|opravdu\s+|fakt\s+|skutecn\w*\s+)?(?:clovek|human|zivy|ziva|realn\w*|skutecn\w*)/,
  /(?:mluvim|pisu|bavim se|komunikuji|povidam si|jednam)\s+(?:tady\s+|ted\s+)?(?:s\s+)?(?:clovekem|zivym clovekem|robotem|botem|strojem|ai|umelou inteligenc\w*|pocitacem)/,
  /(?:odpovida|pise|mluvi|reaguje)\s+(?:mi\s+|nam\s+|tady\s+)?(?:vubec\s+)?(?:clovek|zivy clovek|robot|bot|stroj|ai|umela inteligence|pocitac)/,
  /(?:je (?:to|tohle|tu)|jde o)\s+(?:vlastne\s+)?(?:ai|umela inteligence|robot\w*|bot\w*|chatbot\w*|automat\w*|nejak\w* program\w*)/,
  // „kdo mi tady odpovídá" ano; „kdo fotí zápasy" ne — proto je zájmeno povinné.
  /(?:kdo|s kym)\s+(?:mi|nam|tady|tu|ted|vlastne)\s+(?:mi\s+|tady\s+|vlastne\s+)?(?:odpovida|pise|mluvi|to pise)/,
  /(?:za tebou|za vami|na druhe strane)\s+(?:je|sedi|stoji)\s+(?:clovek|nekdo|zivy clovek)/,
  /generuje\s+(?:tvoje|vase|ty)?\s*(?:odpovedi|odpoved|text)\s*(?:ai|umela inteligence)?/,
  /(?:jsi|jste)\s+(?:ty\s+)?(?:opravdu\s+|fakt\s+|skutecne\s+)?lukas\b/,
  // EN — přímé
  /(?:are|r)\s+(?:you|u)\s+(?:an?\s+)?(?:ai|a\.i|artificial intelligence|robot|bot|chatbot|machine|computer|program)/,
  /(?:are|r)\s+(?:you|u)\s+(?:a\s+)?(?:human|person|real|real person|alive)/,
  /(?:am i|are we)\s+(?:talking|speaking|chatting|writing)\s+(?:to|with)\s+(?:an?\s+)?(?:ai|bot|robot|human|person|machine)/,
  /(?:is this|is it)\s+(?:an?\s+)?(?:ai|bot|chatbot|robot|automated|human|real person)/,
  /(?:who|what)\s+am i\s+(?:talking|speaking|chatting)\s+(?:to|with)/,
  // Formální / strojové prověrky transparentnosti
  /ai[\s_-]*disclosure/,
  /disclosure[\s_-]*probe/,
  /(?:regulation\s*)?\(?eu\)?\s*2024\s*\/?\s*1689/,
  /artificial intelligence act/,
  /(?:article|clanek|cl)\s*\.?\s*50\s*(?:\(1\)|\s*odst)/,
  /(?:zakon\w*|pravo|narizeni)\s+(?:mam|mame)?\s*(?:pravo)?\s*vedet.{0,40}(?:ai|umel\w* inteligenc\w*)/,
];

function normalize(value) {
  return String(value || '')
    .toLocaleLowerCase('cs-CZ')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9()/._\s-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function isAiDisclosureQuestion(value) {
  const text = normalize(value);
  if (!text) return false;
  return DISCLOSURE_PATTERNS.some((re) => re.test(text));
}

// Anglicky odpovíme jen tomu, kdo anglicky psal. Čeština je výchozí.
export function isEnglishQuestion(value) {
  const raw = String(value || '');
  if (/[áčďéěíňóřšťúůýž]/i.test(raw)) return false;
  const text = normalize(raw);
  const czech = /(^|\s)(?:jsi|jste|ses|jsem|mluvim|odpovida|clovek|umela|inteligence|foceni|fotis|portret|galerie|web|prosim|dekuji|zapas)(\s|$)/.test(text);
  if (czech) return false;
  return /(^|\s)(?:are|you|is|this|the|human|ai|bot|talking|message|request|regulation|whether|response|system)(\s|$)/.test(text);
}

const CZECH_WORD_RE = /(^|\s)(?:jsem|jsi|jste|ses|mam|mate|chci|prosim|dekuji|dekuju|dobry|ahoj|jak|kde|kdy|kolik|proc|kdo|ktery|ktera|muj|moje|foceni|fotis|fotite|portret|portrety|galerie|zapas|zapasy|web|weby|clovek|clovekem|umela|inteligence|robot|robotem)(\s|$)/;

export function looksCzech(value) {
  const raw = String(value || '');
  if (/[áčďéěíňóřšťúůýž]/i.test(raw)) return true;
  return CZECH_WORD_RE.test(normalize(raw));
}

// Text musí odpovídat skutečnosti: běžná konverzace se na serveru neukládá,
// krátký souhrn jen po výslovném souhlasu (visitor memory), člověk = Lukáš přes kontakt.
export const AI_DISCLOSURE_REPLY =
  'Ano, jsem AI — Lukáš AI, hybridní AI agent na webu Lukáše Drštičky. '
  + 'Moje odpovědi i hlas generuje umělá inteligence, nejsem člověk a nevydávám se za něj. '
  + 'Běžná konverzace se na serveru neukládá; krátký souhrn si pamatuji jen tehdy, když k tomu dáte souhlas. '
  + 'S Lukášem osobně se spojíte přes kontakt na webu nebo na lukas.drsticka@gmail.com. '
  + 'Jinak vám rád poradím s focením, galeriemi zápasů nebo projekty FrameMind.';

export const AI_DISCLOSURE_REPLY_EN =
  'Yes, I am an AI — Lukáš AI, the hybrid AI agent on Lukáš Drštička\'s website. '
  + 'My answers and my voice are generated by artificial intelligence; I am not a human and I do not pretend to be one. '
  + 'Regular conversations are not stored on the server; I only remember a short summary if you give consent. '
  + 'You can reach Lukáš personally via the contact section or at lukas.drsticka@gmail.com. '
  + 'Otherwise I am happy to help with photography, match galleries or FrameMind projects.';

// `earlier` = dřívější zprávy návštěvníka. Kdo předtím psal česky, dostane češtinu,
// i když anglický probe jen odněkud vložil.
export function buildAiDisclosureReply(value, earlier = []) {
  if (!isEnglishQuestion(value)) return AI_DISCLOSURE_REPLY;
  const spokeCzechBefore = (Array.isArray(earlier) ? earlier : [])
    .some((message) => {
      const content = typeof message === 'string' ? message : message?.content;
      return Boolean(content) && looksCzech(content);
    });
  return spokeCzechBefore ? AI_DISCLOSURE_REPLY : AI_DISCLOSURE_REPLY_EN;
}
